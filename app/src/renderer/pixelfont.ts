function build([top, pattern]: [number, string]): string[] {
  const src = pattern.split('/');
  const width = Math.max(1, ...src.map(r => r.length));
  const rows = Array<string>(FONT_ROWS).fill('.'.repeat(width));
  src.forEach((r, i) => { if (top + i < FONT_ROWS) rows[top + i] = r.padEnd(width, '.'); });
  return rows;
}

/** Znak `base` z podmienionymi wierszami (akcenty, ogonki, kreski). */
function marked(base: string[], marks: Record<number, string>): string[] {
  const w = base[0].length;
  return base.map((r, i) => (marks[i] === undefined ? r : marks[i].padEnd(w, '.').slice(0, w)));
}

